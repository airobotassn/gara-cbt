import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 2 })
await page.goto('http://127.0.0.1:8124/games/feel-cari.html?lang=ko'); await page.waitForTimeout(300)
await page.evaluate(() => { window.MGBridge.submit = () => {} })
await page.click('#startBtn'); await page.waitForTimeout(100)
await page.evaluate(() => { $('brOv').classList.add('hidden'); LI = 10; loadLevel(); document.querySelector('.s[data-k=lidar]').click(); document.querySelector('.s[data-k=ultra]').click(); bot.x = 10 * CELL + 13; bot.y = 5 * CELL + 13; bot.a = 0; joyX = 1; joyY = 0 })
await page.waitForTimeout(2500)
const a = await page.evaluate(() => ({ hits, x: +bot.x.toFixed(1), y: +bot.y.toFixed(1), touching }))
console.log('2.5s 정면으로 밀기 →', JSON.stringify(a))
await page.evaluate(() => { joyX = 0; joyY = 1 })
await page.waitForTimeout(1500)
const b = await page.evaluate(() => ({ hits, x: +bot.x.toFixed(1), y: +bot.y.toFixed(1), touching }))
console.log('1.5s 옆(아래)으로 밀기 →', JSON.stringify(b))
await page.evaluate(() => { joyX = -1; joyY = 0 })
await page.waitForTimeout(700)
await page.evaluate(() => { joyX = 1; joyY = 0 })
await page.waitForTimeout(1200)
const c = await page.evaluate(() => ({ hits, x: +bot.x.toFixed(1), y: +bot.y.toFixed(1) }))
console.log('떨어졌다 다시 박기 →', JSON.stringify(c))
await page.evaluate(() => { joyX = 0; joyY = 0; stop() })
await page.waitForTimeout(100)
const box = await page.evaluate(() => { const v = document.getElementById('view').getBoundingClientRect(); return { x: v.left, y: v.top, width: v.width, height: v.height } })
await page.screenshot({ path: 'tmp/_ft-dark.png', clip: box })
await browser.close()
