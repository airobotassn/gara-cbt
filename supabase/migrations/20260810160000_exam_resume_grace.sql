-- 응시 복구를 "실제로 다시 볼 수 있는" 복구로 만든다.
--
-- 앞선 20260810140000 의 복구는 **같은 응시로 돌아가되 started_at 을 그대로 뒀다.** 그래서:
--   · 밤 8시에 PC 가 뻗어 문의 → 다음 날 아침 처리 → 그 사이 12시간이 제한시간에서 흘러가 **이미 만료**
--   · 응시 마지막 날 사고 → 처리 시점엔 **응시 기간 자체가 닫혀** 아예 못 들어감
-- 관리자가 24시간 상주하지 않는 한 복구가 이름만 복구였다. 두 컬럼으로 고친다.
-- 🔁 **아래 두 결정은 그 뒤 뒤집혔다(2026-08-26 확인). 이 파일 머리말을 그대로 믿지 말 것.**
--    당시엔 답안이 제출 때 한 번에 올라간다는 전제로 ① '남은 시간만 복원' 을 포기하고 ② 응시 기간과
--    무관한 별도 기한을 두려 했다. 그 뒤 하트비트(exam-session)가 draft_answers 를 계속 저장하게 되면서
--    전제가 사라졌고, 지금 코드는 이렇다:
--      · **남은 시간이 보존된다.** start-exam 이 재진입 시점에 `started_at = 지금 − (끊긴 시각까지 쓴 시간)`
--        으로 옮긴다. 나가 있던 시간은 안 깎이고 답안·문항도 그대로다.
--      · **아래 resume_deadline 컬럼은 읽는 곳도 쓰는 곳도 없다.** 복구된 응시도 회차의 응시 기간
--        안에서만 들어갈 수 있다(그게 응시자 안내 `seb.voided_how`·`prep.resume_*` 와도 맞는 말이다).
--    ⚠️ 컬럼과 인덱스는 **남겨둔다** — 드롭하는 마이그레이션을 새로 쓰는 것보다, 안 쓰는 이유를 여기
--       적어두는 편이 싸다. 되살릴 거면 위 '응시 기간 안에서만' 안내 문구부터 같이 고칠 것.
alter table public.exam_attempts
  -- 복구된 응시가 들어갈 수 있는 기한 — **지금은 아무도 안 읽는다**(위 머리말 참고).
  add column if not exists resume_deadline timestamptz;

-- 재진입 판정이 매번 훑는 조건 — 복구된 채 아직 기한이 남은 응시.
create index if not exists exam_attempts_resume_idx
  on public.exam_attempts (user_id, resume_deadline)
  where reinstated_at is not null;
