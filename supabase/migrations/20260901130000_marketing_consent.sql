-- 광고·마케팅 수신 동의 (2026-09-01)
--
-- 정보통신망법 §50 은 영리목적 광고성 정보(뉴스레터·프로모션)를 보내려면 **명시적 사전 동의**를 받으라고 한다.
-- 로그인 화면의 고지문("로그인 시 동의한 것으로 간주")은 명시적 동의가 아니다 — 그래서 약관 동의 게이트에
-- **선택 체크박스**를 하나 더 두고 그 결과를 여기에 남긴다.
--
-- ⛔ **필수 동의와 한 칸에 담지 말 것.** 광고 수신 동의는 서비스 이용의 조건이 될 수 없어서
--    (동의를 거부해도 서비스를 다 쓸 수 있어야 한다) 약관·연령 동의와 반드시 분리된 항목이어야 한다.
--    `terms_agreed_at` 하나로 둘을 표현하면 "동의 안 하면 못 쓴다"가 되어 위법이 된다.
--
-- ⛔ **이 컬럼을 `grant update (…)` 목록에 넣지 말 것.** profiles 는 화이트리스트 방식이라 새 컬럼은
--    자동으로 service role 전용이고, `agree-terms` 함수만 쓴다. 목록에 넣는 순간 브라우저가
--    체크박스를 누르지 않고도 자기 동의를 써넣을 수 있다(terms_agreed_at 과 같은 이유).
--
-- ⚠️ **시각을 남기는 게 핵심이다** (boolean 이 아니다). 두 가지 때문이다:
--    ① 분쟁 시 "언제 동의받았나"의 입증 책임이 우리에게 있다.
--    ② §50⑧ 은 **2년마다 수신동의 여부를 재확인**하라고 한다 — 그 기준이 이 시각이다.
--    철회하면 null 로 되돌린다(= 지금은 수신 거부 상태).
--
-- ⚠️ **아직 철회 수단이 없다.** 실제로 광고 메일을 보내기 전에 두 가지가 반드시 있어야 한다:
--    ① 메일 제목의 `(광고)` 표기 ② 메일마다 수신거부 링크 + 마이페이지 토글.
--    받아만 두고 보내면 안 된다.

alter table public.profiles add column if not exists marketing_agreed_at timestamptz;

-- 발송 대상을 뽑는 쿼리 전용. 동의자는 소수일 것이므로 부분 인덱스가 작다.
create index if not exists profiles_marketing_opted_in_idx
  on public.profiles (id) where marketing_agreed_at is not null;
