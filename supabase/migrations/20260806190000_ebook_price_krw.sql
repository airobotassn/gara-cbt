-- 이북 가격(ebooks.price) 단위 정정 — 달러로 들어간 값을 원(KRW)으로 환산한다.
--
-- 문제: 컬럼은 처음부터 원(KRW) 정수로 정의돼 있었는데(20260723090000_ebooks.sql), 실제로 들어간 값은
--   달러 기준이었다(0 · 1 · 1 · 2). 화면도 `$` 로 찍고 있어서 아무도 못 알아챘다.
--   결제를 붙이는 순간 이 숫자가 그대로 토스 `amount.value`(KRW) 로 나가므로 **1원 결제 요청**이 된다
--   (카드 최소 결제금액 미만이라 애초에 승인이 안 된다).
--
-- 환산 기준: **$1 = 1,500원** (2026-08-06 결정). 응시료도 같은 기준이다
--   → 20260806180000_exam_fees_krw_tiers.sql 참고. 통화는 원 하나로 못박았고 환율 곱셈은 쓰지 않는다.
--
-- ⚠️ `price < 100` 가드가 중요하다. 이미 원화로 들어간 값(1500 등)에 또 1500을 곱하면
--    225만원짜리 이북이 된다. 달러 스케일(두 자리 이하)일 때만 환산한다 → 재실행해도 안전하다.
--    무료(0)는 곱해도 0이지만 updated_at 을 건드리지 않으려고 함께 제외한다.
--
-- 이후 가격 변경은 마이그레이션이 아니라 **관리자 화면**(이북 탭 · 가격 입력칸)에서 원 단위로 한다.

update public.ebooks
   set price = price * 1500,
       updated_at = now()
 where price > 0
   and price < 100;
