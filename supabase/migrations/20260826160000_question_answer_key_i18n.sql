-- 모양: {"en": ["Edge Computing", "Edge"], "ja": ["エッジコンピューティング"], ...}
--   · **언어별 배열**이다(원본 answer_key 의 줄바꿈 목록과 같은 뜻). 줄바꿈 문자열로 받지 않는 이유 =
--     번역기가 줄바꿈을 지우거나 합쳐 놓는 일이 잦은데, 배열이면 항목 경계가 모델 출력에서 흔들리지 않는다.
--   · ko 는 담지 않는다 — 한국어 단일 출처는 원본 컬럼(answer_key)이다(prompt·choices 와 같은 규칙).
--   · 개수는 원문과 같을 필요가 없다. 표기 변형(엣지컴퓨팅/엣지 컴퓨팅)은 언어마다 가짓수가 다르고,
--     보기(choices)와 달리 **순서가 정답 번호를 가리키지 않아서** 개수가 어긋나도 위험이 없다.
--     채점은 합집합에 들어 있는지만 본다.

