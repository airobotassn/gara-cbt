--
-- 출처 = 이미 저장소에 있는 지도 파일 public/geo/adm1/<ISO>.json (Natural Earth 10m admin-1).
-- 이 SQL 은 그 파일들에서 code 만 뽑은 **생성물**이다. 지도 파일을 갈면 여기도 다시 뽑아야 한다.
--
-- ⚠️ 이름(6개국어)과 폴리곤은 DB 에 넣지 않는다 — 그 파일 안에 이미 있고, 여기 또 넣으면 두 벌이 되어
--    한쪽만 고쳐지는 순간 화면과 서버가 다른 말을 한다. **DB = 코드(정답지) · 파일 = 그림과 이름(표시).**
-- ⚠️ 코드 모양이 나라마다 다르다 — ISO 3166-2(KR-11), Natural Earth 임시코드(AE-X01~), 점 표기(ES.CE),
--    이름 그대로(Est, 부르키나파소)까지 섞여 있다. 그래서 '국가 = 코드 앞 두 글자' 로 파싱하면 안 되고,
--    어느 나라 것인지를 country_code 컬럼에 **적어 둔다**(전 세계 3504개 중 나라 간 코드 충돌은 0건).
-- ⚠️ 지도가 그 코드로 지역을 식별하고 랭킹도 그 코드로 묶인다. 우리 정답지가 같은 값을 써야 맞물린다.
