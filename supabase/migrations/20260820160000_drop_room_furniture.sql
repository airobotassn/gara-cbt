-- ── 1) 상점에서 가구를 내린다 ───────────────────────────────────────────────
-- ⚠️ active=false 로 숨기는 게 아니라 **행을 지운다.** 숨기기만 하면 `kind='furniture'` 를 읽는
--    코드가 나중에 되살아났을 때 조용히 다시 나타난다. 소유자가 0이라 FK 로 걸릴 것도 없다.
delete from shop_catalog where kind = 'furniture';

-- ── 2) 혹시 남은 소유·구매 기록 정리 ────────────────────────────────────────
-- 실측 0건이지만 멱등하게 지운다(이 파일을 다른 환경에 돌려도 같은 상태가 되도록).
--   ⚠️ shop_purchase 는 **결제 감사 로그**라 원래 지우지 않는 표다. 가구는 0건인 게 확인돼서
--      지우는 것이고, 1건이라도 있었으면 남겨야 한다(코인이 빠진 기록이므로).
delete from user_cosmetics where part_key like 'fur\_%';
delete from shop_purchase  where part_key like 'fur\_%';

-- ── 3) 방 배치 표를 드롭한다 ────────────────────────────────────────────────
-- 슬롯(어느 자리에 무슨 가구)만 담던 표라 가구가 없으면 담을 것이 없다.
drop table if exists user_rooms;

