-- ============================================================
-- 채팅 번역 — "시도했지만 엔진이 못 한 글"을 기록할 수 있게
--
--   왜 필요한가(2026-08-13 실측):
--     엣지 번역기가 **특정 문장에서 그냥 터진다.** 예: "i'm sitting around 340 lol, season just
--     started though" → UnknownError. `lol` 이 문장 중간에 있으면 재현되고, 빼면 번역된다.
--     엔진 결함이라 우리가 고칠 수 없다.
--
--   문제는 그 뒤였다. 창고에 아무 흔적이 안 남으니 `chat_translation_pending` 이 그 글을
--   **매 초 다시 후보로 올렸고**, 워커는 영원히 같은 글을 시도하며 로그를 채웠다.
--   글이 늘어날수록 이 낭비가 쌓인다.
--
--   그래서 **body 를 null 로 한 행 = "시도했고 못 했다"** 는 표식으로 쓴다.
--     · pending 의 anti-join 이 그 행을 보고 후보에서 뺀다 → 재시도가 멈춘다
--     · 사용자 요청 경로는 body 가 null 인 행을 걸러서 반환한다 → 화면엔 원문이 남는다
--     · created_at 이 있으니 나중에 "오래된 실패는 다시 시도" 를 넣고 싶으면 그걸 보면 된다
--
--   ⚠️ 번역문이 빈 문자열인 것과 다르다 — 빈 문자열은 "번역했는데 결과가 비었다" 이고,
--      null 은 "번역을 못 했다" 다. 화면 동작이 갈리므로 섞지 말 것.
--
--   멱등(재실행 안전) — schema.sql 에 동일 DDL 존재.
-- ============================================================

alter table chat_translations alter column body drop not null;

comment on column chat_translations.body is
  '번역문. null = 엔진이 이 글을 번역하지 못했다(재시도 중단 표식). 빈 문자열과 다르다.';
