--
-- 왜: 그림이 아직 없다. 고르면 폴백 한 장(옛 한복 소녀)이 Lv.1~7 자리에 똑같이 일곱 번 뜨는
--     빈 껍데기라, 첫 진입 선택 화면에서 "셋 중 하나 고르세요" 를 시켜놓고 둘은 그림이 없다.
--
-- ⛔ 행을 지우지 않는다. 지우면 이미 가진 사람의 `user_cosmetics` 가 고아가 되고, 그림이 도착해
--    다시 올릴 때 값·진열순서를 처음부터 다시 정해야 한다. active 만 내리면 그대로 되돌아온다.
-- ⚠️ 되살릴 때는 `src/lib/hubCosmetics.ts` 의 `CHAR_SERIES` 에도 계열을 같이 넣어야 한다 —
--    그 목록이 보관함(가진 것)과 카탈로그를 못 받았을 때의 폴백을 만든다.
-- ⚠️ 진열 중 캐릭터가 **0종이 되면 신규 회원이 첫 화면에 갇힌다**(hub_choose_character 의 (2a)).
--    계열 a 남·여 2종이 남으므로 이 마이그레이션은 그 선을 넘지 않는다.
-- ⚠️ 이미 b·c 를 가진(=고른) 사람은 그대로 입고 있다 — 진열을 내려도 갈아입기는 막지 않는다.
update shop_catalog
   set active = false
 where part_key in ('char_b_m', 'char_b_f', 'char_c_m', 'char_c_f');
