-- 시험환경 점검 독려 메일 본문 교체 (2026-09-18 지시 · PPT `관리자 페이지 수정사항` 5페이지)
--
-- CARIS 현황 › 시험환경 점검 › 메일 보내기의 본문 기본값(site_settings.mail_nudge_body)을 PPT 문구로 바꾼다.
-- 제목은 PPT 에 없어 그대로 둔다. 치환자는 {name}·{examDate}·{link} 만 쓴다({round}·{tier} 는 안 쓰지만 여전히 채워진다).
--
-- ⚠️ PPT 문구는 "아래 기한 내에" 라고 하면서 기한이 본문에 없었다 → "점검 기한" 한 줄을 넣었다(2026-09-18 지시 "넣어").
--    기한 = 시험일 전날. 시험일 당일은 응시가 열리는 날이라 점검을 그날 하게 두면 응시 불가 안내와 어긋난다.
-- ⚠️ 관리자가 사이트 정보에서 이미 손본 값이 있어도 **덮어쓴다** — PPT 가 이 문구로 바꾸라는 지시라서다.
--    이 시점 프로덕션 값은 2026-08-11 시드 문구 그대로였다.

update public.site_settings set value =
  E'안녕하세요, {name} 님. CARIS 자격검정센터입니다.\n{name} 님께서는 다가오는 시험일 {examDate}에 진행되는 CARIS에 접수하셨으나, 현재 ''시험환경 사전 점검''을 완료하지 않은 것으로 확인되었습니다.\n\n본 자격시험은 안정적인 온라인 응시를 위해 시험 전 PC 환경점검 및 보안프로그램 설치를 의무화하고 있습니다. 아래 기한 내에 점검을 완료하지 않으실 경우, [시험 당일 응시 불가 / 당일 발생하는 모든 시스템 오류에 대한 책임은 수험자 본인에게 있음]을 안내해 드립니다.\n\n점검 기한: {examDate} 전날까지\n\n원활한 시험 응시를 위해 지금 바로 아래 안내에 따라 점검을 완료해 주시기 바랍니다.\n\n{link}\n\n감사합니다.',
  updated_at = now()
where key = 'mail_nudge_body';

-- 행이 없으면(시드가 안 돈 환경) 새로 넣는다 — 위 update 는 0건이고 이 insert 가 받는다.
insert into public.site_settings (key, value)
select 'mail_nudge_body',
  E'안녕하세요, {name} 님. CARIS 자격검정센터입니다.\n{name} 님께서는 다가오는 시험일 {examDate}에 진행되는 CARIS에 접수하셨으나, 현재 ''시험환경 사전 점검''을 완료하지 않은 것으로 확인되었습니다.\n\n본 자격시험은 안정적인 온라인 응시를 위해 시험 전 PC 환경점검 및 보안프로그램 설치를 의무화하고 있습니다. 아래 기한 내에 점검을 완료하지 않으실 경우, [시험 당일 응시 불가 / 당일 발생하는 모든 시스템 오류에 대한 책임은 수험자 본인에게 있음]을 안내해 드립니다.\n\n점검 기한: {examDate} 전날까지\n\n원활한 시험 응시를 위해 지금 바로 아래 안내에 따라 점검을 완료해 주시기 바랍니다.\n\n{link}\n\n감사합니다.'
where not exists (select 1 from public.site_settings where key = 'mail_nudge_body');
