-- 허브 배경 두 장 — 같은 고궁의 낮과 밤 (2026-08-20)
--
-- 옛 배경(`skin_palace` / public/hub/bg.png)은 **비판매 기본** 한 장뿐이라, 꾸미기의 '배경' 칸이
-- 상점에서는 비어 있고 보관함에서는 이미 입고 있는 한 장만 떠서 **누를 것이 없었다.**
-- 이제 두 장이다: 낮은 전원이 쓰는 기본, 밤은 코인으로 사는 상품.
--
-- ⚠️ **낮(기본)은 값이 0이어야 한다.** 화면은 아무것도 장착 안 한 사람과 모르는 값이 저장된 사람을
--    전부 목록 첫 항목으로 떨어뜨린다(`skinByPart`). 그 첫 항목에 값을 매기면 신규 회원 화면에
--    배경이 없다. `hub_equip` 도 price=0 을 소유 검사 예외로 두고 있어 되돌아올 길이 된다.
-- ⚠️ 두 스킨은 **UI 한 벌을 공유하고 배경만 다르다**(hub.css 가 값 블록 하나를 둘이 쓰고
--    `--skin-bg` 만 각자 덮는다). 그래서 밤을 사도 판·게이지·도장·아이콘은 그대로다.
-- ============================================================================

-- ── 1) 새 배경 두 장 ────────────────────────────────────────────────────────
-- 밤 배경 값(300)은 시작값이다 — 관리자 화면(WORLD ARENA > 꾸미기 관리)에서 바꿀 수 있다.
--   출석 1회가 10코인이라 대략 한 달치다.
insert into shop_catalog (part_key, price, kind, sort_order, active) values
  ('skin_palace_day',     0, 'skin', 100, true),
  ('skin_palace_night', 300, 'skin', 110, true)
on conflict (part_key) do nothing;

-- ── 2) 옛 배경을 입고 있던 사람을 낮으로 옮긴다 ─────────────────────────────
-- ⚠️ 안 옮겨도 화면은 안 깨진다(모르는 값이면 목록 첫 항목으로 떨어진다). 그래도 옮기는 이유는,
--    안 옮기면 보관함에서 **아무것도 '착용 중'으로 안 보여** 자기가 뭘 입고 있는지 화면이 말을 못 한다.
update user_characters
   set equipped   = equipped || jsonb_build_object('skin', 'skin_palace_day'),
       updated_at = now()
 where equipped->>'skin' = 'skin_palace';

-- ── 3) 옛 배경 정리 ─────────────────────────────────────────────────────────
-- 비판매(active=false)였으므로 산 사람이 있을 수 없지만, 수기 지급 흔적까지 멱등하게 치운다.
delete from user_cosmetics where part_key = 'skin_palace';
delete from shop_catalog  where part_key = 'skin_palace';
