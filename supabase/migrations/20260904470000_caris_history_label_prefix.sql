-- 2026-09-04 · CARIS 이력 이름표에 `C-` 접두사 + 세 자리 채움 (2026-09-04 지시)
--
--   문항 이력 표를 셋에서 하나로 합치면서(question_history) 세 제도의 이름표가 한 컬럼에 섞였는데,
--   CARIS 만 모양이 달랐다 — 옛 cbt_question_events.number 가 int 였던 탓에 맨숫자로 들어갔다:
--     leveltest  L1-001 … L7-037
--     term       T-002 … T-072
--     caris      2 · 7 · 100 · 233     ← 이것만 접두사 없음
--   한 표에 섞여 있으면 어느 제도 것인지 눈으로 안 갈린다. `C-002` 형식으로 맞춘다.
--
--   ⚠️ **세 자리로 채우는 이유** = label 이 text 라 안 채우면 정렬이 `"100" < "98"` 이 된다.
--      지금 문항 번호는 1~233 이라 세 자리면 충분하고, 넘치면 그대로 붙는다(잘리지 않는다).
--
--   ⚠️ 대상은 **숫자로만 된 label** 뿐이다(26건). 나머지 30건은 문항 하나가 아닌 작업(엑셀 import 22 ·
--      세트 뽑기 등 edit 8)이라 label 이 비어 있다 — 건드리지 않는다.
--      ⛔ 조건을 안 걸고 밀면 이미 `C-` 가 붙은 행에 두 번 붙는다(`C-C-100`).
--
--   ⚠️ label 로 조회하는 곳은 용어(term)뿐이다(admin/reform 의 이력 검색이 `T-001` 로 eq 매칭).
--      CARIS 이력은 문제은행(scope)으로 찾으므로 형식을 바꿔도 검색이 안 깨진다.
--
--   앞으로 쌓이는 것은 admin/index.ts 의 cbtLabel() 이 같은 규칙으로 만든다 — 한쪽만 고치면
--   옛 행과 새 행의 모양이 갈린다.

begin;

update question_history
   set label = 'C-' || lpad(label, 3, '0')
 where kind = 'caris' and label ~ '^[0-9]+$';

commit;
