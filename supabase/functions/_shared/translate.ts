// 채팅 번역 공용 판정.
//
//  ⛔ **서버 번역 엔진은 없다(2026-08-13 결정).** Azure·구글 어댑터가 잠깐 있었지만 걷어냈다.
//     번역은 전부 **우리 기계의 Edge 브라우저**(tools/translate-worker)가 한다 — 온디바이스라
//     공짜·무제한이고, 외부 계정·카드·API 키가 하나도 필요 없다.
//
//  그래서 이 파일에 남은 건 "번역할 가치가 있는 글인가" 판정 하나뿐이다.
//  서버(chat-translate)와 워커가 같은 판정을 써야 해서 여기 둔다.
//
//  ⚠️ 서버 엔진이 없으므로 **어떤 (방 × 언어) 조합의 첫 요청은 반드시 빈손**이다.
//     그 요청이 수요 등록이 되고, 워커가 1초 뒤 채우고, 프론트가 재시도로 집어간다
//     (ChatBoard 의 fetchWithRetry). 워커가 꺼져 있으면 번역이 안 되고 원문이 남는다.

/**
 * 번역할 가치가 있는 글인가.
 *  · 글자(letter)가 하나도 없으면 번역해도 결과가 같다 — 이모지·숫자·기호만 있는 줄.
 *  · 2자 이하는 맥락이 없어 감지도 번역도 신뢰할 수 없다("ㅋㅋ", "ok", "gg").
 * 채팅은 짧은 글이 절반이라 이 필터 하나가 워커 일감을 크게 줄인다.
 */
export function isTranslatable(text: string | null | undefined): boolean {
  const s = (text ?? '').trim()
  if (s.length <= 2) return false
  return /\p{L}/u.test(s)
}
